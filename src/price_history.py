"""Local price-history recorder + a naive next-value predictor.

Steam's public priceoverview endpoint has no history parameter -- it only ever returns the
CURRENT lowest/median price (see steam_prices.py). This module builds a history itself, one
snapshot per genuinely-fresh (non-cache-hit) Steam price fetch, starting from whenever this
feature first runs. It is NOT retroactive: a skin/wear you've never looked up before has no
history, and this module says so plainly rather than fabricating one.

Format is JSON Lines (one snapshot per line), same rationale as outcomes.py: cheap appends
(no read-modify-write of the whole file), and a corrupt trailing line can be skipped on read
without losing every prior snapshot. Lives in data/ (NOT cache/) for the same reason
outcomes.py does -- this is accumulated history that can't be regenerated by re-downloading
anything, unlike cache/price_cache.json's disposable, TTL'd snapshots.
"""
from dataclasses import dataclass
import json
import threading
import time
from pathlib import Path

DATA_DIR = Path(__file__).resolve().parent.parent / "data"
HISTORY_FILE = DATA_DIR / "price_history.jsonl"

MIN_HISTORY_POINTS = 5  # below this, predict_next_price() refuses -- same "refuse, don't
# fabricate" gate shape as learning.py's MIN_TRAINING_SAMPLES
PREDICT_HORIZON_SECONDS = 24 * 3600  # how far ahead the trend line is extrapolated

_write_lock = threading.Lock()  # mirrors outcomes.py's _write_lock -- serializes appends
# within this process; cross-process safety is the same documented, accepted limitation as
# outcomes.py and price_cache.json already have.


@dataclass
class PredictionResult:
    predicted_price: float
    slope_per_day: float
    r_squared: float
    n_points: int
    method: str
    horizon_hours: float


def record_snapshot(market_hash_name: str, currency: int, data: dict) -> None:
    """Appends one price snapshot. `data` is the same dict steam_prices.get_price() returns
    ({"lowest_price", "median_price", "volume"}) -- called right after a real (non-cached)
    fetch succeeds there, never on a cache hit (a cache hit isn't new information)."""
    if not data:
        return
    entry = {
        "ts": time.time(),
        "market_hash_name": market_hash_name,
        "currency": currency,
        "lowest_price": data.get("lowest_price"),
        "median_price": data.get("median_price"),
        "volume": data.get("volume"),
    }
    DATA_DIR.mkdir(parents=True, exist_ok=True)
    line = json.dumps(entry)
    with _write_lock:
        with open(HISTORY_FILE, "a", encoding="utf-8") as f:
            f.write(line + "\n")


def get_history(market_hash_name: str, currency: int) -> list[dict]:
    """All recorded snapshots for this exact name+currency, oldest first. Reads/filters the
    whole file in Python -- fine at this data scale (hundreds to low thousands of rows over
    realistic usage), same reasoning as outcomes.load_outcomes(). Skips corrupt lines rather
    than raising, same as outcomes.py."""
    if not HISTORY_FILE.exists():
        return []
    out = []
    with open(HISTORY_FILE, encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if not line:
                continue
            try:
                entry = json.loads(line)
            except json.JSONDecodeError:
                continue
            if entry.get("market_hash_name") == market_hash_name and entry.get("currency") == currency:
                out.append(entry)
    out.sort(key=lambda e: e["ts"])
    return out


def predict_next_price(history: list[dict], field: str = "lowest_price") -> PredictionResult | None:
    """Fits a plain linear regression (price ~ timestamp) over the recorded points and
    extrapolates PREDICT_HORIZON_SECONDS ahead. Returns None below MIN_HISTORY_POINTS usable
    points -- never fabricates a trend from too little data. This is a naive baseline
    (coursework-level, not a real forecasting model): it assumes a straight-line trend
    continues, which real skin prices very often don't.

    Lazily imports scikit-learn (same pattern as learning.py's train()/predict_roi()) so this
    module -- and everything that imports it, including steam_prices.py -- stays importable
    with zero third-party packages installed until this specific function is actually called."""
    points = [(e["ts"], e[field]) for e in history if e.get(field) is not None]
    if len(points) < MIN_HISTORY_POINTS:
        return None

    from sklearn.linear_model import LinearRegression
    import numpy as np

    xs = np.array([[p[0]] for p in points], dtype=float)
    ys = np.array([p[1] for p in points], dtype=float)
    model = LinearRegression()
    model.fit(xs, ys)
    r_squared = model.score(xs, ys)

    now = points[-1][0]
    target_ts = now + PREDICT_HORIZON_SECONDS
    predicted = float(model.predict([[target_ts]])[0])
    slope_per_day = float(model.coef_[0]) * 86400

    return PredictionResult(
        predicted_price=predicted,
        slope_per_day=slope_per_day,
        r_squared=float(r_squared),
        n_points=len(points),
        method="linear_trend",
        horizon_hours=PREDICT_HORIZON_SECONDS / 3600,
    )
